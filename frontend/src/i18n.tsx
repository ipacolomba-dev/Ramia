const dict: Record<Lang, Record<string, string>> = { it, en };

interface LocaleCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  L: (itVal: string | null | undefined, enVal: string | null | undefined) => string;
}

const LocaleContext = createContext<LocaleCtx>({
  lang: "it",
  setLang: () => {},
  t: (k) => k,
  L: (itVal) => itVal || "",
});

const LOCALE_KEY = "app_locale";

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("it");

  useEffect(() => {
    (async () => {
      const saved = await storage.getItem<Lang>(LOCALE_KEY, "it");
      if (saved === "it" || saved === "en") setLangState(saved);
    })();
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    storage.setItem(LOCALE_KEY, l);
  };

  const value = useMemo<LocaleCtx>(() => {
    const t = (key: string, vars?: Record<string, string | number>) => {
      let s = dict[lang][key] ?? dict.it[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      }
      return s;
    };
    const L = (itVal: string | null | undefined, enVal: string | null | undefined) =>
      lang === "en" && enVal ? enVal : itVal || "";
    return { lang, setLang, t, L };
  }, [lang]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useT() {
  return useContext(LocaleContext);
}
